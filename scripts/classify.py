"""Archived classification runner. Re-runs the packaged inputs with the captured parameters.

Do not edit this file inside a package; reproduce.py calls it as archived.

Usage:
  python classify.py --package PKG --engine transformers|vllm|ollama|hosted_api|mock
                     [--sample N] [--out DIR] [--revision SHA] [--base-url URL]
                     [--model-name NAME] [--api-key-env VAR] [--ollama-tag TAG]
Exit codes: 0 ok, 3 verification mismatch, 4 inputs incomplete.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import (canonical_json, field_value, load_yaml, now_iso, read_jsonl, read_records, sha256_text,
                    write_jsonl)
from adapters import get_adapter
from adapters.base import RunSpec
from extract import INVALID, extract
from model_profiles import get_profile
import render_inputs as ri


def build_spec(m: dict, args: argparse.Namespace) -> RunSpec:
    prof = get_profile(field_value(m, "model_profile.name") or "default")
    tkw, extra = {}, {}
    for fname, spec in (prof.get("fields") or {}).items():
        v = field_value(m, f"model_profile.{fname}")
        if v in (None, "unknown"):
            continue
        if spec.get("template_kwarg"):
            tkw[spec["template_kwarg"]] = v
        if spec.get("ollama_option"):
            extra[spec["ollama_option"]] = v
    dec = {k: field_value(m, f"decoding.{k}") for k in ("temperature", "top_p", "top_k", "seed", "max_tokens")}
    hosted = field_value(m, "hosted_api.parameters")
    return RunSpec(
        repo_id=getattr(args, "repo_id", None) or field_value(m, "model.repo_id"),
        revision=args.revision or _known(field_value(m, "model.revision")),
        precision=_known(field_value(m, "decoding.precision")),
        quantization=_known(field_value(m, "model.quantization")),
        ollama_tag=args.ollama_tag or _known(field_value(m, "model.ollama_tag")),
        ollama_digest=_known(field_value(m, "model.ollama_digest")),
        decoding=dec, batch_size=int(_known(field_value(m, "decoding.batch_size")) or 1),
        deterministic=field_value(m, "decoding.batch_invariant") is True,
        template_kwargs=tkw, extra_options=extra,
        base_url=args.base_url or _known(field_value(m, "hosted_api.base_url")),
        model_name=args.model_name or _known(field_value(m, "hosted_api.model_name")),
        api_key_env=args.api_key_env or _known(field_value(m, "hosted_api.api_key_env")),
        hosted_parameters=hosted if isinstance(hosted, dict) else {})


def _known(v):
    return None if v in (None, "", "unknown") else v


def load_requests(pkg: Path, m: dict, sample: int | None) -> list[dict]:
    rel = field_value(m, "prompt.rendered_inputs_file")
    if not rel or rel == "unknown":
        print("ERROR: package has no rendered inputs; it cannot be re-run.", file=sys.stderr)
        raise SystemExit(4)
    archived = read_jsonl(pkg / rel)
    complete = field_value(m, "prompt.rendered_inputs_complete") is True
    reqs = archived
    if not complete:
        sp = str(field_value(m, "prompt.user_template") or "")
        data_rel = field_value(m, "data.path")
        if "#user_template" in sp and data_rel not in (None, "unknown", "not_shared"):
            spec_file = pkg / sp.split("#", 1)[0]
            full = ri.render_spec_file(spec_file, pkg / data_rel, field_value(m, "data.id_column") or "id")
            by_id = {r["request_id"]: r for r in full}
            for a in archived:
                if a["request_id"] not in by_id or by_id[a["request_id"]]["sha256"] != a["sha256"]:
                    print(f"ERROR: re-rendered input for {a['request_id']} does not match the archived sample.",
                          file=sys.stderr)
                    raise SystemExit(3)
            reqs = full
        elif not sample:
            print("ERROR: only a sample of rendered inputs is archived and the prompt cannot be re-rendered. "
                  "Use --sample N to re-run the archived sample.", file=sys.stderr)
            raise SystemExit(4)
    for r in reqs:
        if sha256_text(canonical_json(r["messages"])) != r["sha256"]:
            print(f"ERROR: rendered input {r['request_id']} fails its hash check.", file=sys.stderr)
            raise SystemExit(3)
    if sample:
        reqs = ri.deterministic_sample(reqs, sample)
    return reqs


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--package", type=Path, required=True)
    ap.add_argument("--engine", required=True)
    ap.add_argument("--sample", type=int)
    ap.add_argument("--out", type=Path)
    ap.add_argument("--revision")
    ap.add_argument("--repo-id")
    ap.add_argument("--base-url")
    ap.add_argument("--model-name")
    ap.add_argument("--api-key-env")
    ap.add_argument("--ollama-tag")
    args = ap.parse_args()
    pkg = args.package.resolve()
    out = (args.out or pkg / "reproduction").resolve()
    m = load_yaml(pkg / "manifest.yaml")
    reqs = load_requests(pkg, m, args.sample)
    spec = build_spec(m, args)
    adapter = get_adapter(args.engine)(spec)

    checks = {}
    want = _known(field_value(m, "model.chat_template_sha256"))
    have = adapter.chat_template_sha256()
    checks["chat_template"] = {"manifest": want, "engine": have}
    if want and have and want != have:
        print(f"ERROR: chat template hash mismatch (manifest {want}, engine {have}).", file=sys.stderr)
        return 3
    for r in reqs:
        if r.get("rendered_sha256"):
            text = adapter.render(r["messages"])
            if text is not None and sha256_text(text) != r["rendered_sha256"]:
                print(f"ERROR: rendered prompt for {r['request_id']} differs from the archived rendering.",
                      file=sys.stderr)
                return 3
    started = now_iso()
    results = adapter.generate([r["messages"] for r in reqs])
    rule = field_value(m, "outputs.label_extraction_rule")
    rule = dict(rule) if isinstance(rule, dict) else {"type": "exact"}
    if field_value(m, "study.task_type") == "multi_label":
        rule.setdefault("multi_label", True)
        rule.setdefault("separator", field_value(m, "study.multi_label_separator") or ";")
    label_set = field_value(m, "study.label_set")
    label_set = label_set if isinstance(label_set, list) else None
    raw_rows, labels = [], {}
    for r, res in zip(reqs, results):
        text = res.get("raw_text") or res.get("text") or ""
        if rule.get("type") not in ("harmony_final",):
            text = res.get("text") or ""
        got = extract(text, rule, label_set, [str(i) for i in r["item_ids"]] or [r["request_id"]])
        labels.update(got)
        raw_rows.append({"request_id": r["request_id"], "text": res.get("text"), "raw_text": res.get("raw_text"),
                         "reasoning": res.get("reasoning"), "meta": res.get("meta")})
    write_jsonl(out / "raw_outputs.jsonl", raw_rows)
    write_jsonl(out / "labels.jsonl", [{"id": k, "label": list(v) if isinstance(v, tuple) else v}
                                       for k, v in labels.items()])
    info = {"started_at": started, "ended_at": now_iso(), "engine": args.engine, "versions": adapter.versions(),
            "n_requests": len(reqs), "sample": args.sample, "spec": {k: v for k, v in vars(spec).items()
                                                                  if k != "api_key_env"},
            "api_key_env_name": spec.api_key_env, "checks": checks,
            "n_invalid": sum(1 for v in labels.values() if v == INVALID)}
    (out / "run_info.json").write_text(json.dumps(info, indent=2, default=str) + "\n", encoding="utf-8")
    print(f"Wrote {len(labels)} labels to {out / 'labels.jsonl'} ({info['n_invalid']} invalid).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
